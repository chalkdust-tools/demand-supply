/* ---------------------------------------------------------
   （ここから下はさわらなくてOK）
   正解がいつも1番目にならないよう、選択肢の順番を入れかえます。
   問題文から順番を決めるので、アプリとワークシートで同じ並びになります。
   SHIFT・PQ の選択肢は、いつも同じ並びのほうが見やすいので入れかえません。
   --------------------------------------------------------- */
window.choiceOrder = function (Q) {
  if (Q.choices === SHIFT || Q.choices === PQ || Q.fixed) return Q.choices.slice();
  let h = 0;
  for (const c of Q.q) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  const a = Q.choices.slice();
  for (let i = a.length - 1; i > 0; i--) {
    h = (h * 1103515245 + 12345) >>> 0;
    const j = h % (i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};
